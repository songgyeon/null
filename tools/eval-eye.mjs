/* 품질 자의 눈 — 워커를 안 본다.
   node에서 직접 부를 일은 없다. tools/eval.mjs가 쓴다.

   ── 왜 갈라놨나 ──
   이 파일이 존재하는 이유는 하나다. 전에는 tools/eval.mjs가
   `import { isLeak, isMeta } from '../worker.js'`를 했다. 판정을 한 군데로
   모으는 것은 보통 옳지만 **여기서는 틀렸다.**

     워커 필터가 못 본다
     → 평가기가 같은 필터를 가져다 쓴다
     → 평가기도 못 본다
     → 둘이 동시에 「문제 없음」이라고 한다

   실제로 그런 줄이 있었다. `update성의 없다고 놀린 게 아니라…` —
   워커의 isLeak도 isMeta도 못 잡고, 그 눈을 빌린 자도 못 잡았다.
   사람이 손으로 찍어둔 정답지만 그게 문제라고 알려줬다.

   자는 생산 코드와 **다른 눈**이어야 한다. 그래야 둘의 엇갈림이 정보가 된다.
   자가 보는데 워커가 못 보면 그건 워커가 고칠 목록이다(D단계).

   ── 축이 다르다 ──
   워커는 **문구 목록**으로 본다 — 「The instructions」, 「I should」, 「유저」.
   자는 **문자 구성**으로 본다 — 대소문자, 로마자와 한글이 붙은 자리, 조각의 모양.
   같은 것을 두 번 보는 게 아니라 다른 각도에서 본다. 그래서 한쪽이 놓친 것을
   다른 쪽이 잡을 수 있다.

   ── 이 파일의 규칙 ──
   1. worker.js를 import하지 않는다. 앞으로도.
   2. 규칙을 넓히기 전에 작가 문구집(docs/dialogue-corpus.md) 2,640줄에
      대고 돌려서 오탐 0을 확인한다. 여기 있는 것은 전부 그렇게 확인했다.
   3. 놓치는 것보다 멀쩡한 대사를 위반으로 세는 쪽이 나쁘다. */

/* ── ① 소문자 로마자가 한글에 붙었다 ──
   기록에서 로마자가 한글에 붙은 자리가 서른셋이다. 그중 서른하나가
   고유명사고 — LP는 · Sia예요 · Kisses예요 · NCT면 · Spirit이면 —
   전부 대문자로 시작하거나 통째로 대문자다. 제목과 약칭이 그렇게 생겼다.

   소문자로만 된 것은 둘뿐이었고 **둘 다 샌 것**이었다.
     update성의 없다고 놀린 게 아니라…
     …'invite'를 같이 쓴다" and the available place is…

   사람은 한글 옆에 소문자 영단어를 붙여 쓰지 않는다. 붙는다면 그건
   낱말이 아니라 조각이다. 작가 문구집 2,640줄에서 0건.

   대문자가 하나라도 섞이면 안 잡는다 — iPhone·LP·NCT가 그 자리다. */
const LATIN_RUN = /[A-Za-z][A-Za-z'’]*/g;
const HANGUL = /[가-힣]/;

function gluedLower(t) {
  const s = String(t || "");
  LATIN_RUN.lastIndex = 0;
  let m;
  while ((m = LATIN_RUN.exec(s))) {
    if (!/^[a-z'’]+$/.test(m[0])) continue;         // 대문자가 섞였으면 고유명사다
    const before = m.index > 0 ? s[m.index - 1] : "";
    const after = s[m.index + m[0].length] || "";
    if (HANGUL.test(before) || HANGUL.test(after)) return m[0];
  }
  return null;
}

/* ── ② 소문자 로마자 낱말이 셋 이상 이어진다 ──
   ①은 한글에 **붙어야** 잡는다. 한글이 아예 없는 영어 혼잣말은 못 잡는다.
   그 자리를 이게 맡는다.

   제목은 Title Case라 소문자가 이어지지 않는다 —
   「Don't Delete the Kisses」에서 소문자는 the 하나,
   「I Don't Think That I Like Her」는 하나도 없다.
   반면 영어 산문은 관사·전치사·조동사가 줄줄이 소문자다:
   「…say "…" and the available place is …」.

   셋으로 잡은 것은 실측이다. 둘도 문구집에서 0건이었지만 셋이 더 안전하다 —
   소문자 두 낱말짜리 제목(「the xx」)이 없다고 장담할 수 없다. */
function lowerRun(t, need) {
  const words = String(t || "").match(LATIN_RUN) || [];
  let run = 0;
  for (const w of words) {
    run = /^[a-z'’]+$/.test(w) ? run + 1 : 0;
    if (run >= (need || 3)) return true;
  }
  return false;
}

/* ── ③ 대사 안에 조각이 있다 ──
   **워커는 줄머리만 본다**(`^[[{]\s*["'[{]`). 그게 워커의 맹점이다 —
   앞에 한 마디 붙은 채로 새면 안 걸린다.
   자는 아무 데나 본다. 그게 이 축이 독립인 지점이다.

   시각 표기를 조심한다. 인물이 「3시 40분」이 아니라 「3:40」이라고 쓸 수 있고
   이 게임은 시계가 중요하다. 그래서 콜론만으로는 안 잡고 **따옴표에 붙은
   콜론**만 본다. 웃는 표시(:D, :))도 같은 이유로 안 걸린다.
   문구집 2,640줄에서 0건. */
const FRAGMENTS = [
  [/"\s*:/, "따옴표에 붙은 콜론"],
  [/"\s*,\s*"/, "따옴표로 이어붙인 목록"],
  [/\[\s*"/, "여는 대괄호와 따옴표"],
  [/"\s*\]/, "닫는 대괄호와 따옴표"],
  [/\}\s*[`'"]*\s*$/, "줄 끝의 닫는 중괄호"],
  [/```/, "코드 울타리"],
];

function fragment(t) {
  const s = String(t || "");
  for (const [re, why] of FRAGMENTS) if (re.test(s)) return why;
  return null;
}

/* 대사가 아닌 것이 말풍선으로 나갔나. 셋을 한 자리에서 본다 —
   부르는 쪽이 갈래를 알아야 D단계에서 무엇을 고칠지 정할 수 있다. */
export function seesLeak(text) {
  const g = gluedLower(text);
  if (g) return { code: "GLUED_LATIN", why: `한글에 붙은 소문자 「${g}」` };
  const f = fragment(text);
  if (f) return { code: "FRAGMENT", why: f };
  if (lowerRun(text, 3)) return { code: "EN_PROSE", why: "소문자 로마자 세 낱말 연속" };
  return null;
}

/* ── ④ 인용·전언 어미 ──
   금지한 것은 전언이다 — 「간대요」「하래요」처럼 남의 말을 옮기는 어미.
   그런데 두 글자만 보면 「그래요.」가 걸린다. 「그래요」는 「그렇다」의
   활용이고 이 게임에서 제일 흔한 정상 대사 중 하나다.
   옛 기록 17건 중 7건이 그거였다 — 「2.7 → 0.8건으로 좋아졌다」는
   오탐끼리 비교한 숫자였고 폐기했다.

   형태소 분석기 없이 할 수 있는 것은 「끝이 대요·래요인데 전언이 아닌
   낱말」을 빼는 것이다. 목록을 늘리는 편이 규칙을 넓히는 것보다 안전하다. */
const TAIL = /(대요|래요)\.$/;
const TAIL_OK = /(그래요|이래요|저래요|노래요|빨래요|미래요|장래요|기대요|반대요|상대요|절대요|모래요)\.$/;

/* ── ㄹ 받침 앞의 래요는 의지지 전언이 아니다 ──
   작가 문구집에서 다섯 줄이 걸려서 알았다. 낱말 목록으로는 못 막는 갈래다.
     먹을래요 · 갈래요 · 마실래요 · 정할래요 · 마실래요
   전부 「-(으)ㄹ래요」 — 내가 하겠다는 말이다. 전언 「-(으)래요」(남이
   그러라고 했다는 말)와 글자만 같다.

   가르는 자리는 앞 음절의 받침이다.
     하래요 · 오래요 · 먹으래요   받침 없음 또는 ㅇ  → 전언
     갈래요 · 먹을래요 · 마실래요  ㄹ 받침            → 의지

   「팔래요」처럼 진짜 둘 다인 것이 있다(팔겠다 / 팔라고 했다). 사람도
   앞뒤 없이는 못 가른다. 그럴 때는 안 잡는 쪽으로 간다 — 멀쩡한 대사를
   위반으로 세는 쪽이 더 나쁘다.

   대요에는 이 규칙을 안 건다. 「-ㄹ대요」라는 어미가 없다. */
const RIEUL = t => {
  const m = String(t || "").match(/(.)래요\.$/);
  if (!m) return false;
  const c = m[1].charCodeAt(0) - 0xAC00;
  return c >= 0 && c < 11172 && c % 28 === 8;      // 종성 ㄹ
};

export const seesTail = t =>
  TAIL.test(String(t || "")) && !TAIL_OK.test(String(t || "")) && !RIEUL(t);

/* ── 상담사·비서 말투 ── */
const HELPER_WORDS = ["도움이 되", "정리해 드리", "정리하자면", "다음과 같", "말씀해 주시",
  "괜찮으시다면", "어떠신가요", "제안드", "추천드", "함께 알아", "어떠세요?"];
export const seesHelper = t => HELPER_WORDS.some(w => String(t || "").includes(w));

/* ── 유저의 속을 단정하기 ──
   전에는 이랬다.
     /(당신|선생님|너)(은|는|이|가)?\s*[^.!?]{0,12}(했잖|했을 거|하고 싶|힘들|외로|슬프|피곤하죠)/
   작가 문구집에서 다섯 줄이 걸렸는데, 보면 **정반대**였다.
     선생님 하고 싶은 대로 해도 돼요.
     오늘은 선생님 하고 싶은 거 해요.
     선생님이 말하고 싶을 때요. / 억지로는 안 물을게요.
   유저를 대신 쓴 것이 아니라 유저에게 맡기는 말이다. 이 게임에서 제일
   좋은 대사 축에 드는 것들을 위반으로 세고 있었다.

   ── 「했잖아요」를 뺀 이유 ──
   「상견례는 선생님이 먼저 말했잖아요」가 날조인지 기억인지는 **앞 대화를
   봐야 안다.** 실제로 유저가 말했으면 멀쩡한 대사고, 안 했으면 날조다.
   자는 그걸 못 가린다. 못 가리는 것을 세면 그 숫자는 아무 말도 아니다.
   과거 행동 날조는 G3의 trace JSON(무엇이 실제 사실이었나)이 있어야 잰다.

   ── 남긴 것 ──
   **앞뒤와 무관하게 틀린 것만** 남긴다. 인물은 유저의 속을 볼 수 없다.
   그러니 유저의 감정이나 욕망을 확인 어미로 단정하는 것은 언제나 틀렸다.
   「힘드셨죠」「외로우셨죠」「보고 싶었잖아요」「사실은 …」.
   문구집 2,640줄에서 0건. */
const USER_INNER = [
  /(힘들|힘드|외롭|외로우|슬프|슬퍼|피곤하|지치|지쳤|괴롭|서운하|불안하)(죠|시죠|셨죠|잖아요|었잖아요|겠죠)/,
  /(하고 싶|보고 싶|가고 싶|듣고 싶)(잖아요|었잖아요|어 하|어하|으셨죠)/,
  /(?:당신|선생님|너)(?:은|는|이|가|도)?\s*[^.!?]{0,10}(?:속으로|사실은|진짜로는)/,
];
export const seesUserWrite = t => USER_INNER.some(re => re.test(String(t || "")));

/* ── 받은 것을 없던 일로 만들기 ──
   선물 사건 뒤에 「그런 거 받은 적 없는데요」가 나오면 그 사건이 통째로
   사라진다. 사건당으로 세는 이유가 이것이다 — 줄당으로 세면 선물을 적게
   주는 판이 유리해진다.

   물건 이름을 댄 부정과 이름 없는 부정을 가른다. 생산 필터가 다섯 조건이
   전부 맞을 때만 자르기로 한 것과 같은 구별이다(D단계). 자는 자르지 않고
   세기만 하므로 둘 다 세되 갈래를 남긴다. */
/* ── 방향을 지킨다 ──
   유저가 준 선물을 인물이 없던 일로 만드는 것은 「**받은** 적 없다」다.
   「준 적 없다」는 반대 방향(인물이 유저에게 준 것)이다. 둘을 한 자루에
   넣었더니 「민현이한테 **잘해준 적 없**다니까요」가 선물 부정으로 세어졌다 —
   선물과 아무 상관 없는 말이다.

   「그런 거 없어요」류도 뺐다. 문구집의 「그런 적 없어요.」가 걸렸는데
   그건 딴 얘기를 부정하는 멀쩡한 대사다. 무엇을 부정하는지가 안 적힌
   문장은 자가 판정할 수 없다.

   남은 것은 문구집 2,640줄과 기록 1,907줄에서 오탐 0이다. */
const DENY_RECV = /(받은 적(?:이)? 없|안 받았|못 받았|받지 않았|받은 기억(?:이)? 없)/;
/* 「준」 앞에 한글이 붙으면 「잘해준」「사준」처럼 다른 동사의 활용이다 */
const DENY_GIVE = /(?:^|[\s"'“”「(,])(?:준 적(?:이)? 없|드린 적(?:이)? 없)|안 줬|주지 않았/;

export function seesDenial(text, item, dir) {
  const s = String(text || "");
  const re = dir === "from_char" ? DENY_GIVE : DENY_RECV;
  if (!re.test(s)) return null;
  const name = String(item || "").trim();
  /* 물건 이름을 댄 부정이 제일 나쁘다 — 그 사건을 콕 집어 없앤 것이다.
     이름 없는 부정은 딴 얘기일 수 있어 갈래를 나눠 센다. */
  if (name && s.includes(name)) return { code: "DENY_NAMED", why: `「${name}」을 부정했다` };
  return { code: "DENY_VAGUE", why: "받고 준 사실을 부정했다" };
}

/* ── 메아리 ──
   유저 문장의 알맹이를 그대로 되돌린 것. */
export function seesEcho(text, prevUser) {
  const p = String(prevUser || "");
  if (p.length < 6) return false;
  const core = p.replace(/[^가-힣]/g, "");
  if (core.length < 6) return false;
  return String(text || "").replace(/[^가-힣]/g, "").includes(core.slice(0, 6));
}

